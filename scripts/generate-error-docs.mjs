// Generates apps/web/content/docs/errors.mdx from the B4_ERRORS registry so
// the public error-code reference can never drift from the code. Reads the
// built @b4run/sdk dist (run after `pnpm build`). The check-docs guard
// enforces that the committed output lists exactly the registry's codes.
import { writeFileSync } from "node:fs"
import { resolve } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const repoRoot = resolve(fileURLToPath(import.meta.url), "..", "..")
const sdkDist = pathToFileURL(resolve(repoRoot, "packages/sdk/dist/index.js")).href
const outPath = resolve(repoRoot, "apps/web/content/docs/errors.mdx")

const { B4_ERRORS } = await import(sdkDist)

const rows = Object.values(B4_ERRORS)
  .sort((a, b) => a.code.localeCompare(b.code))
  .map((descriptor) => {
    const docs = descriptor.docsPath ? `[${descriptor.docsPath}](${descriptor.docsPath})` : "None"
    return `| \`${descriptor.code}\` | ${descriptor.title} | ${docs} |`
  })

const body = `{/* GENERATED by scripts/generate-error-docs.mjs. Do not edit by hand. */}

# Error Codes

Every user-facing B4.run failure carries a stable \`B4_Exxxx\` code. You'll see
the code wherever the failure shows up (CLI stderr, HTTP/SSE error bodies and
permission-denial tool results), so you can search for it and link to it.

Codes are grouped by range: \`E1xxx\` config / \`b4 check\`, \`E2xxx\` sandbox,
\`E3xxx\` permissions, \`E4xxx\` model / provider, and \`E5xxx\` runtime / import.
A code without a docs link is still a stable identifier you can search for.

| Code | Meaning | Docs |
| --- | --- | --- |
${rows.join("\n")}
`

writeFileSync(outPath, body)
console.log(`[generate-error-docs] wrote ${rows.length} code(s) to ${outPath}`)
